//go:build ignore

package main

import (
	"crypto/sha256"
	"fmt"
	goformat "go/format"
	"os"
	"strconv"
	"strings"
	"unicode/utf8"
)

const (
	glyphListPath     = "../../testdata/adobe-glyphlist.txt"
	glyphUnicodePath  = "glyph_unicode.go"
	generatedFileMode = 0o644
)

func main() {
	if err := generateGlyphUnicode(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generateGlyphUnicode() error {
	source, err := os.ReadFile(glyphListPath)
	if err != nil {
		return fmt.Errorf("read Adobe Glyph List: %w", err)
	}
	var generated strings.Builder
	generated.WriteString("// Code generated by go run glyph_generate.go; DO NOT EDIT.\n")
	fmt.Fprintf(&generated, "// Source: %s\n// SHA-256: %x\n", glyphListPath, sha256.Sum256(source))
	generated.WriteByte('\n')
	for line := range strings.Lines(string(source)) {
		if !strings.HasPrefix(line, "#") {
			break
		}
		generated.WriteString("//" + strings.TrimPrefix(line, "#"))
	}
	generated.WriteString("\npackage parser\n\nvar glyphUnicode = map[string]string{\n")
	seen := make(map[string]struct{})
	for line := range strings.Lines(string(source)) {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		name, values, found := strings.Cut(line, ";")
		if !found || name == "" || values == "" {
			return fmt.Errorf("invalid Adobe Glyph List entry %q", line)
		}
		if _, duplicate := seen[name]; duplicate {
			return fmt.Errorf("duplicate Adobe glyph %q", name)
		}
		seen[name] = struct{}{}
		var text strings.Builder
		for value := range strings.FieldsSeq(values) {
			scalar, err := strconv.ParseUint(value, 16, 32)
			if err != nil {
				return fmt.Errorf("glyph %q has invalid Unicode scalar %q: %w", name, value, err)
			}
			if !utf8.ValidRune(rune(scalar)) {
				return fmt.Errorf("glyph %q has invalid Unicode scalar %q", name, value)
			}
			text.WriteRune(rune(scalar))
		}
		fmt.Fprintf(&generated, "%q: %s,\n", name, strconv.QuoteToASCII(text.String()))
	}
	generated.WriteString("}\n")
	formatted, err := goformat.Source([]byte(generated.String()))
	if err != nil {
		return fmt.Errorf("format Unicode glyph table: %w", err)
	}
	if err := os.WriteFile(glyphUnicodePath, formatted, generatedFileMode); err != nil {
		return fmt.Errorf("write Unicode glyph table: %w", err)
	}
	return nil
}
